from langchain_openai import ChatOpenAI
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import JsonOutputParser

from app.core.config import settings
from app.investigation.state import InvestigationState

verify_prompt = ChatPromptTemplate.from_messages([
    ("system", """You are a verification analyst. Your job is to cross-check conclusions against evidence.

You will receive:
- The original question
- Patterns and explanations generated by an analyst
- The original structured and document evidence

For each explanation, check:
1. Is it directly supported by the provided evidence?
2. Are any statistics or numbers traceable to the SQL results?
3. Are there claims that go beyond what the evidence shows?

Return a JSON object with:
- "verified_explanations": list of explanations that are well-supported
- "unverified_explanations": list of explanations lacking evidence support
- "confidence": your assessed confidence level — "high", "medium", or "low"
- "issues": list of specific issues found (e.g., "Claim X has no supporting data")
"""),
    ("human", """Question: {question}

Patterns found:
{patterns}

Explanations:
{explanations}

Structured Evidence:
{structured_evidence}

Document Evidence:
{document_evidence}
""")
])


def get_llm():
    return ChatOpenAI(
        model="gpt-4o-mini",
        temperature=0,
        openai_api_key=settings.OPENAI_API_KEY,
    )


async def verify_findings(state: InvestigationState) -> dict:
    """Cross-check the analysis conclusions against the retrieved evidence."""
    llm = get_llm()
    chain = verify_prompt | llm | JsonOutputParser()

    structured_str = "\n".join(
        f"- {e.get('content', '')}" for e in state.get("structured_evidence", [])
    ) or "None"

    document_str = "\n".join(
        f"- {e.get('content', '')}" for e in state.get("document_evidence", [])
    ) or "None"

    patterns_str = "\n".join(f"- {p}" for p in state.get("patterns", [])) or "None"
    explanations_str = "\n".join(f"- {e}" for e in state.get("explanations", [])) or "None"

    result = await chain.ainvoke({
        "question": state["question"],
        "patterns": patterns_str,
        "explanations": explanations_str,
        "structured_evidence": structured_str,
        "document_evidence": document_str,
    })

    new_confidence = result.get("confidence", state.get("confidence", "low"))
    verified = result.get("verified_explanations", [])
    issues = result.get("issues", [])

    current_limitations = state.get("limitations", [])
    updated_limitations = current_limitations + issues

    return {
        "confidence": new_confidence,
        "explanations": verified if verified else state.get("explanations", []),
        "limitations": updated_limitations,
        "retry_count": state.get("retry_count", 0) + 1,
        "current_node": "verify_findings",
    }

